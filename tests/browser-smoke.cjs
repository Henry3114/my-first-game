const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs/promises');
const { existsSync } = require('node:fs');
const path = require('node:path');

(async () => {
  const root = path.resolve(__dirname, '..');
  const results = path.join(root, 'test-results');
  await fs.mkdir(results, { recursive: true });
  const server = http.createServer(async (req, res) => {
    try {
      const filename = path.resolve(root, '.' + new URL(req.url, 'http://test').pathname.replace(/\/$/, '/index.html'));
      if (!filename.startsWith(root + path.sep)) throw Error('outside root');
      const mime = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml' };
      res.setHeader('Content-Type', mime[path.extname(filename)] || 'application/octet-stream');
      res.end(await fs.readFile(filename));
    } catch { res.writeHead(404); res.end('Not found'); }
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    const executablePath = process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
    browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    const url = `http://127.0.0.1:${server.address().port}`;
    const readSave = () => page.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')));
    await page.clock.install();
    await page.goto(url);
    await page.locator('h1').waitFor();
    await page.screenshot({ path: path.join(results, 'desktop.png'), fullPage: true });
    assert.equal(await page.locator('[role=dialog]').count(), 0, 'no forced onboarding');
    assert.equal(await page.locator('.product-card').count(), 3);
    await page.locator('.product-card [data-action="bake:roll"]').click();
    await page.clock.runFor(7000);
    assert.equal(await page.locator('.stock-count b').first().textContent(), '6');
    await page.locator('[data-action="fulfill"]').click();
    assert.equal(await page.locator('[data-testid=cash]').textContent(), '¥430');
    assert.equal(await page.locator('[data-action="fulfill"]').isDisabled(), true);
    await page.locator('[data-action="bake:toast"]').click();
    await page.clock.runFor(10000);
    await page.locator('[data-action="open"]').click();
    await page.locator('[data-action="bake:croissant"]').click();
    await page.clock.runFor(5000);
    await page.locator('[data-action="pause"]').click();
    const paused = await readSave();
    await page.clock.runFor(10000);
    assert.equal((await readSave()).minute, paused.minute);
    await page.locator('[data-action="pause"]').click();
    await page.clock.runFor(103000);
    await page.getByRole('dialog').waitFor();
    assert.match(await page.getByRole('dialog').textContent(), /今日营业结余/);
    let save = await readSave();
    assert.equal(save.phase, 'closed'); assert.ok(save.lastSummary.served > 0);
    await page.getByRole('dialog').locator('[data-action="next"]').click();
    await page.locator('[data-action="upgrades"]').click();
    await page.locator('[data-action="upgrade:oven"]').click();
    assert.equal((await readSave()).upgrades.oven, 1);
    await page.locator('[data-action="theme:rose"]').click();
    await page.reload();
    await page.locator('.shop-scene').waitFor();
    assert.equal(await page.locator('.oven-slots > *').count(), 2);
    assert.equal(await page.locator('.theme-rose').count(), 1);
    assert.match(await page.locator('.day-badge').textContent(), /02/);
    await page.locator('.sidebar [data-action="recipes"]').click();
    assert.equal(await page.locator('.product-card').count(), 6);
    await page.locator('[data-action="journal"]').click();
    assert.equal(await page.locator('.history-row').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    console.log('PASS desktop: bake, order, sales, pause, automatic close, next day, upgrades, reload, recipes and journal');

    await page.locator('.topbar [data-action="settings"]').click();
    const downloadEvent = page.waitForEvent('download');
    await page.locator('[data-action="export"]').click();
    const download = await downloadEvent;
    const exported = path.join(results, 'save.json');
    await download.saveAs(exported);
    const payload = JSON.parse(await fs.readFile(exported, 'utf8'));
    assert.equal(payload.day, 2);
    const beforeImport = (await readSave()).cash;
    await page.locator('#import-save').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') });
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('格式不正确'));
    assert.equal((await readSave()).cash, beforeImport);
    payload.cash += 123;
    page.once('dialog', d => d.accept());
    await page.locator('#import-save').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(payload)) });
    await page.locator('.shop-scene').waitFor();
    assert.equal((await readSave()).cash, beforeImport + 123);
    assert.deepEqual(errors, []);
    console.log('PASS save export/import, malformed import preserves original, no browser errors');

    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const mobile = await mobileContext.newPage();
    mobile.on('pageerror', e => errors.push(e.message));
    await mobile.clock.install();
    await mobile.goto(url);
    await mobile.locator('h1').waitFor();
    await mobile.screenshot({ path: path.join(results, 'mobile.png'), fullPage: true });
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await mobile.locator('.sidebar [data-action="recipes"]').click();
    assert.equal(await mobile.locator('.product-card').count(), 6);
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await mobile.locator('[data-action="upgrades"]').click();
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await mobile.locator('[data-action="journal"]').click();
    assert.equal(await mobile.locator('.regular-card').count(), 2);
    await mobile.locator('.topbar [data-action="settings"]').click();
    await mobile.getByRole('dialog').waitFor();
    await mobile.locator('[data-action="dismiss"]').click();
    await mobile.locator('.sidebar button[data-action="shop"]').click();
    await mobile.locator('.oven-empty').first().click();
    await mobile.clock.runFor(7000);
    await mobile.locator('[data-action="open"]').click();
    await mobile.clock.runFor(6000);
    const mobileVisitor = await mobile.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')).visitors[0].id);
    await mobile.locator(`[data-action="visitor:${mobileVisitor}"]`).click();
    await mobile.locator(`[data-action="greet:${mobileVisitor}"]`).click();
    await mobile.locator(`[data-action="serve:${mobileVisitor}"]`).click();
    assert.ok((await mobile.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')))).cash > 342);
    await mobile.screenshot({ path: path.join(results, 'mobile-live.png'), fullPage: true });
    await mobile.setViewportSize({ width: 320, height: 740 });
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log('PASS mobile: four pages, settings, no horizontal overflow at 390px');
    const engine = await import(path.join(root, 'game.js'));
    const legacy = engine.createGame(42);
    legacy.stock.roll = 6; legacy.stock.toast = 6;
    delete legacy.visitors;
    const interactionContext = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    await interactionContext.addInitScript(save => {
      if (!localStorage.getItem('maijian-bakery-v1')) localStorage.setItem('maijian-bakery-v1', JSON.stringify(save));
    }, legacy);
    const interactive = await interactionContext.newPage();
    interactive.on('pageerror', e => errors.push(e.message));
    await interactive.clock.install();
    await interactive.goto(url); await interactive.locator('h1').waitFor();
    assert.equal(await interactive.locator('[data-testid=cash]').textContent(), '¥360', 'legacy save retained');
    await interactive.evaluate(() => window.originalCanvas = document.querySelector('#bakery-canvas'));
    await interactive.locator('[data-action="open"]').click();
    const visitorId = await interactive.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')).visitors[0].id);
    const sceneAtEntry = await interactive.locator('#bakery-canvas').screenshot();
    await interactive.clock.runFor(6000);
    await interactive.locator(`[data-action="visitor:${visitorId}"]`).click();
    assert.equal(await interactive.evaluate(() => window.originalCanvas === document.querySelector('#bakery-canvas')), true, 'canvas is retained across state updates');
    assert.match(await interactive.locator('.guest-speech').textContent(), /奶油餐包/);
    const sceneAtCounter = await interactive.locator('#bakery-canvas').screenshot();
    assert.notDeepEqual(sceneAtEntry, sceneAtCounter, 'scene changes with actual customer movement');
    await interactive.locator(`[data-action="greet:${visitorId}"]`).click();
    assert.match(await interactive.locator('.guest-speech').textContent(), /考试/);
    await interactive.locator(`[data-action="wait:${visitorId}"]`).click();
    assert.match(await interactive.locator('.guest-speech').textContent(), /再等一炉/);
    await interactive.locator(`[data-action="recommend:${visitorId}:toast"]`).click();
    assert.match(await interactive.locator('.guest-speech').textContent(), /牛奶吐司/);
    await interactive.locator(`[data-action="serve:${visitorId}"]`).click();
    const customerSave = await interactive.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')));
    const paidVisitor = customerSave.visitors.find(v => v.id === visitorId);
    assert.equal(paidVisitor.stage, 'paying'); assert.equal(paidVisitor.tip, 2);
    assert.equal(customerSave.cash, 360 + paidVisitor.paidAmount);
    await interactive.clock.runFor(500);
    await interactive.screenshot({ path: path.join(results, 'live-customers.png'), fullPage: true });
    await interactive.reload(); await interactive.locator('h1').waitFor();
    assert.equal((await interactive.evaluate(() => JSON.parse(localStorage.getItem('maijian-bakery-v1')))).cash, customerSave.cash, 'paid visit restores without another charge');
    assert.ok(!(await interactive.locator('.visitor-roster').textContent()).includes('undefined'));
    assert.deepEqual(errors, []);
    console.log('PASS live customers: legacy save, persistent scene, dialogue, greeting, waiting, recommendation, real payment and reload');
    // Render the distributed HTML without a server, imports, or sibling files.
    // An opaque sandbox also exercises the storage-denied path used by previews.
    const standaloneContext = await browser.newContext();
    const standalone = await standaloneContext.newPage();
    const externalRequests = [];
    standalone.on('request', r => { if (/^https?:/.test(r.url())) externalRequests.push(r.url()); });
    standalone.on('pageerror', e => errors.push(e.message));
    await standalone.setContent('<!doctype html><html><body></body></html>');
    const bundled = await fs.readFile(path.join(root, 'index.html'), 'utf8');
    assert.ok(!bundled.includes('type="module" src='));
    await standalone.evaluate(html => {
      const frame = document.createElement('iframe');
      frame.setAttribute('sandbox', 'allow-scripts allow-downloads allow-modals');
      frame.srcdoc = html;
      document.body.appendChild(frame);
    }, bundled);
    const preview = standalone.frameLocator('iframe');
    await preview.locator('h1').waitFor();
    await preview.locator('.product-card [data-action="bake:roll"]').click();
    const previewFrame = await (await preview.locator('h1').elementHandle()).ownerFrame();
    await previewFrame.waitForFunction(() => document.querySelector('.stock-count b').textContent === '6', null, { timeout: 15000 });
    assert.equal(await preview.locator('.stock-count b').first().textContent(), '6');
    await preview.locator('[data-action="open"]').click();
    await previewFrame.waitForFunction(() => document.querySelector('[data-testid=cash]').textContent !== '¥342', null, { timeout: 15000 });
    assert.equal(await preview.locator('.status-pill.open').textContent(), '营业中');
    assert.notEqual(await preview.locator('[data-testid=cash]').textContent(), '¥342');
    assert.deepEqual(externalRequests, []);
    assert.deepEqual(errors, []);
    console.log('PASS standalone preview: opaque iframe, storage denied, baking and sales work, zero external requests');
    console.log('Screenshots: test-results/desktop.png and test-results/mobile.png');
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
